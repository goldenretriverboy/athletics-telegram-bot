def score_item(item: SourceItem, watch_terms: list[str]) -> SourceItem:
    haystack = f"{item.title} {item.summary}".lower()
    score = item.score
    for term, value in IMPORTANT_TERMS.items():
        if term in haystack:
            score += value
    for term in watch_terms:
        if term.lower() in haystack:
            score += 15
    item.score = score
    return item


def rank_items(
    items: list[SourceItem],
    watch_terms: list[str],
    limit: int,
    min_score: int | None = None,
) -> list[SourceItem]:
    scored = [score_item(item, watch_terms) for item in items]
    if min_score is not None:
        scored = [item for item in scored if item.score >= min_score]
    return sorted(scored, key=lambda item: item.score, reverse=True)[:limit]
